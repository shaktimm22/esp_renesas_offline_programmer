"""PlatformIO pre-build step: gzip web/index.html into src/web_page.h (a PROGMEM byte array).

The page is compiled into the firmware instead of living on LittleFS, so `uploadfs`
is never needed (it would wipe the stored firmware image and settings).
The header is only rewritten when the page changes, so it does not force a rebuild.
"""

import gzip
import os

try:
    Import("env")  # noqa: F821 - provided by PlatformIO/SCons
    ROOT = env.subst("$PROJECT_DIR")  # noqa: F821
except NameError:  # run directly: python tools/embed_web.py
    ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

SRC = os.path.join(ROOT, "web", "index.html")
DST = os.path.join(ROOT, "src", "web_page.h")


def build():
    with open(SRC, "rb") as f:
        data = gzip.compress(f.read(), compresslevel=9, mtime=0)
    lines = []
    for i in range(0, len(data), 20):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 20]) + ",")
    text = (
        "// Generated by tools/embed_web.py from web/index.html - do not edit.\n"
        "#pragma once\n"
        "#include <Arduino.h>\n\n"
        f"static const size_t WEB_PAGE_GZ_LEN = {len(data)};\n"
        "static const uint8_t WEB_PAGE_GZ[] PROGMEM = {\n" + "\n".join(lines) + "\n};\n"
    )
    try:
        with open(DST, "r", encoding="ascii") as f:
            if f.read() == text:
                return
    except OSError:
        pass
    with open(DST, "w", encoding="ascii", newline="\n") as f:
        f.write(text)
    print(f"embed_web: {os.path.relpath(SRC, ROOT)} -> {os.path.relpath(DST, ROOT)} ({len(data)} bytes gzipped)")


build()
